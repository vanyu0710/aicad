export function translate(language: Lang, key: string, vars?: Record<string, string | number>): string {
  let text = translations[language]?.[key] ?? translations.zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function useT() {
  const language = useAppStore((state) => state.language);
  return (key: string, vars?: Record<string, string | number>) => translate(language, key, vars);
}
